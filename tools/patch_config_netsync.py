#!/usr/bin/env python3
"""Патч: доводка кооперативного режима (поколение протокола 2).

Что чинится. Три жалобы на кооп имеют разные причины, и все три требуют новых
ручек в конфиге:

1. Дёрганое движение не-хоста. Хост ЗАЩЁЛКИВАЛ последний пришедший ввод и
   интегрировал защёлку каждый тик, а подтверждал сразу самый свежий номер. При
   бурстах TCP один ввод оставался неучтённым, но подтверждённым, — и база
   переигровки у клиента врала на несколько тиков. Лечится очередью ввода:
   `input_queue_len` — её глубина, `input_catchup_max` — сколько пакетов клиент
   имеет право дослать за кадр, если его цикл просел ниже 60 Гц.

2. Чужие сущности дёргались, потому что клиент тянулся к САМОМУ СВЕЖЕМУ снапшоту
   и буфера дрожания не было вовсе. `interp_delay_ms` — насколько часы
   воспроизведения отстают от последнего снапшота (≈1.8 периода при 30 Гц),
   `interp_max_extrapolate_ms` — предел экстраполяции, дальше заморозка
   (деградация, а не лаг — CLAUDE.md §4), `interp_clock_rate` — доля рассинхрона
   часов, съедаемая за секунду.

3. Прах на полу не ездил по сети вообще. `pickup_hz` и `max_pickups_per_snapshot`
   задают отдельный дешёвый канал: прах почти не движется, гнать его с частотой
   снапшота незачем.

Цена. Пользователь разрешил тратить ресурсы на кооп щедрее, поэтому
`snapshot_hz` 20 → 30, а бюджет трафика 30 → 60 КБ/с. Подъём частоты оплачен
заменой сортировки выбором в отборе видимых врагов и отказом от кодирования
снапшота для самого хоста (сервер его всё равно выбрасывал).

Заодно: `smooth_time` и `predict_history_frames` были константами в
net/client.js, а `weapon_flash_time`, `weapon_swing_default`,
`projectile_size_default` и `projectile_spin_rate` — в sim/weapon.js и main.js.
Числа поведения в коде запрещены (CLAUDE.md §3.1), переезжают сюда.

`protocol_version` 1 → 2 поднимается РОВНО ЗДЕСЬ и один раз на все три фичи
этого поколения (кооп, враг-рывкач, турели): формат провода меняется одним
куском, дробить версию по фичам незачем.

Идемпотентен, пишет в обе копии конфига (CLAUDE.md §3.2).

    tools/patch_config_netsync.py --apply
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.join(ROOT, "config", "game_config.json")
LIVE = os.path.join(os.environ.get("ASH_DATA", os.path.join(ROOT, "data")),
                    "game_config.json")

CONTENT_VERSION = 45

NET = {
    # 30 Гц вместо 20: чужие игроки и враги перестают «телепортироваться» между
    # снапшотами настолько заметно, а буфер интерполяции ниже становится дешевле.
    "snapshot_hz": 30,
    # Потолок трафика на клиента. Прежние 30 КБ/с были почти выбраны одним
    # снапшотом, и добавить в него прах было некуда.
    "traffic_budget_kbs": 60,
    # Поколение формата: биты moving/telegraph/swingCtr, каналы праха и турелей.
    "protocol_version": 2,
    # Очередь ввода на хосте. 8 кадров ≈ 133 мс — переживает бурст, но не даёт
    # очереди превратиться в дополнительную задержку управления.
    "input_queue_len": 8,
    # Сколько пакетов ввода клиент досылает за кадр, если просел ниже 60 fps.
    # Без этого он навсегда голодит очередь хоста; с капом переключение вкладки
    # не выстреливает пачкой.
    "input_catchup_max": 3,
    # Задержка воспроизведения чужих сущностей: ≈1.8 периода снапшота при 30 Гц.
    # Выборки штампуются локальными часами клиента, поэтому отдельных «часов,
    # догоняющих хост», не нужно — расходиться нечему, и время воспроизведения
    # считается прямо как netTime - interp_delay.
    "interp_delay_ms": 60,
    "interp_max_extrapolate_ms": 120,
    # Глубина кольца выборок на сущность. Нужно ceil(delay / период снапшота) + 1,
    # иначе время воспроизведения оказывается старше всех хранимых выборок и
    # сущность залипает на самой старой, прыгая при каждом новом снапшоте —
    # то есть ровно тот стук, ради которого буфер и заводится. При 30 Гц и 60 мс
    # это 3, четвёртая — запас на дрожание доставки.
    "interp_samples": 4,
    # Прах почти не движется (только магнит), поэтому едет своим дешёвым каналом.
    "pickup_hz": 10,
    "max_pickups_per_snapshot": 64,
    # Потолок пульсов замаха за такт. Дуговой удар не рождает снаряда, и без
    # события сосед видит немой бой: у хоста меч машет, у клиента он стоит
    # столбом. Прежняя схема (индекс оружия прямо в записи игрока) передавала
    # ОДИН замах на игрока за такт и не отличала повторный удар тем же оружием
    # от предыдущего — анимация проигрывалась один раз за забег.
    #
    # 128 = восемь игроков × шесть стволов, и ещё остаётся на турели, которые
    # бьют из того же слота. Переполнение — потеря косметики, а не лаг.
    "max_swings_per_snapshot": 128,
    # Мёртвая зона пересборки предсказания, пиксели.
    #
    # Позиция едет в снапшоте как int16, то есть округлённая до целого пикселя:
    # худшая ошибка по оси — 0.5 px. Клиент пересобирал предсказание от этой
    # округлённой базы каждый снапшот, и ошибка округления попадала прямо в
    # результат, меняя знак по мере дрейфа истинной позиции хоста относительно
    # целых. Получалась пила ±0.3 px на 30 Гц — глазу невидимая, но «назад» она
    # копится, и на длинной остановке набегает пара пикселей.
    #
    # Если расхождение меньше кванта, сверять нечего: провод физически не может
    # выразить разницу. Держим предсказание как есть. Настоящий рассинхрон
    # (пропущенный ввод, столкновение) даёт кратно больше и порог перешагнёт.
    "reconcile_deadzone_px": 0.75,
    # Было SMOOTH_TIME в net/client.js
    "smooth_time": 0.1,
    # Было HISTORY в net/client.js: ~4 с при 60 fps
    "predict_history_frames": 256,
}

RENDER = {
    # Было FLASH_TIME в sim/weapon.js и net/client.js — одно и то же число в двух
    # файлах, ровно тот случай, ради которого §3.1 запрещает константы в коде.
    "weapon_flash_time": 0.08,
    # Было DEFAULT_SWING в sim/weapon.js
    "weapon_swing_default": 0.22,
    # Было DEFAULT_PROJECTILE_SIZE в sim/weapon.js
    "projectile_size_default": 4,
    # Было PROJ_SPIN_RATE в main.js, рад/с для снарядов со spin='spin'
    "projectile_spin_rate": 14,
    # С какой суммы кучка праха рисуется крупной. По сети едет только этот
    # размерный класс (один байт), сама сумма клиенту не нужна: прах считает
    # хост, а в HUD едет уже доля игрока.
    "ash_big_amount": 12,
    "ash_size_big": 22,
}


def patch(cfg):
    changed = []

    net = cfg.setdefault("net", {})
    for k, v in NET.items():
        if net.get(k) != v:
            changed.append(f"net.{k}: {net.get(k)!r} → {v!r}")
            net[k] = v

    render = cfg.setdefault("render", {})
    for k, v in RENDER.items():
        if render.get(k) != v:
            changed.append(f"render.{k}: {render.get(k)!r} → {v!r}")
            render[k] = v

    if changed and cfg.get("content_version", 0) < CONTENT_VERSION:
        cfg["content_version"] = CONTENT_VERSION
        changed.append(f"content_version → {CONTENT_VERSION}")

    return changed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()

    targets = [REPO] + ([LIVE] if os.path.exists(LIVE) else [])
    for path in targets:
        with open(path, encoding="utf-8") as f:
            cfg = json.load(f)
        changed = patch(cfg)
        print(f"=== {path} ===")
        if not changed:
            print("  (без изменений)")
            continue
        for c in changed:
            print(f"  + {c}")
        if a.apply:
            with open(path, "w", encoding="utf-8") as f:
                json.dump(cfg, f, ensure_ascii=False, indent=2)
                f.write("\n")
            print("  записано")
        else:
            print("  (dry-run, передай --apply)")


if __name__ == "__main__":
    main()
