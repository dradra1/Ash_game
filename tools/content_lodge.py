# --- сборка и проверка -------------------------------------------------------

METRICS = ("runs", "wave", "kills", "kills_type", "ash", "bosses", "shop_buys")
FILTER_FIELDS = ("danger_min", "arena", "character", "curse", "curse_min", "win",
                 "damage_taken_max", "players_min")


def build():
    """Секция `lodge` для конфига: чистые данные, никаких ссылок на python."""
    npcs = []
    for nid, n in NPCS.items():
        item = {"id": nid, "name": n["name"], "title": n["title"],
                "faction": n["faction"], "color": n["color"],
                "texture": n["texture"], "intro": n["intro"],
                "quests": list(n["quests"])}
        if n.get("requires"):
            item["requires"] = n["requires"]
        npcs.append(item)

    quests = {}
    for qid, q in QUESTS.items():
        item = {"npc": q["npc"], "name": q["name"], "desc": q["desc"],
                "brief": q["brief"], "done": q["done"], "lore": q["lore"],
                "reward": q["reward"], "goal": q["goal"]}
        if q.get("requires"):
            item["requires"] = q["requires"]
        quests[qid] = item

    lore = {lid: {"npc": l["npc"], "title": l["title"], "text": l["text"]}
            for lid, l in LORE.items()}

    return {"npcs": npcs, "quests": quests, "lore": lore}


def validate(cfg):
    """Сверка с остальным конфигом: цели заказов ссылаются на реальные сущности.

    Опечатка в `target` не падает нигде — заказ просто никогда не выполнится, и
    заметит это игрок, а не разработчик. Поэтому проверяем здесь и жёстко.
    """
    problems = []
    enemies = cfg.get("enemies") or {}
    bosses = cfg.get("bosses") or {}
    arenas = cfg.get("arenas") or {}
    characters = cfg.get("characters") or {}
    curses = cfg.get("curses") or {}
    factions = cfg.get("factions") or {}
    danger_max = len(cfg.get("danger") or []) - 1

    for nid, n in NPCS.items():
        if n["faction"] not in factions:
            problems.append(f"{nid}: неизвестная фракция {n['faction']}")
        if n["intro"] not in LORE:
            problems.append(f"{nid}: нет вступительного лора {n['intro']}")
        if n.get("requires") and n["requires"] not in QUESTS:
            problems.append(f"{nid}: открывается заказом {n['requires']}, которого нет")
        for qid in n["quests"]:
            if qid not in QUESTS:
                problems.append(f"{nid}: заказа {qid} не существует")
            elif QUESTS[qid]["npc"] != nid:
                problems.append(f"{nid}: заказ {qid} числится за {QUESTS[qid]['npc']}")

    owned = {qid for n in NPCS.values() for qid in n["quests"]}
    for qid in QUESTS:
        if qid not in owned:
            problems.append(f"{qid}: заказ не выдаёт ни один персонаж")

    for qid, q in QUESTS.items():
        if q["lore"] not in LORE:
            problems.append(f"{qid}: открывает несуществующий лор {q['lore']}")
        elif LORE[q["lore"]]["npc"] != q["npc"]:
            problems.append(f"{qid}: лор {q['lore']} принадлежит другому персонажу")
        if q["reward"] <= 0:
            problems.append(f"{qid}: награда должна быть положительной")
        problems += _validate_goal(qid, q["goal"], enemies, bosses, arenas,
                                   characters, curses, danger_max)
        # Цепочка: requires должен вести к предыдущему заказу того же персонажа,
        # иначе заказ либо недостижим, либо открывается не в свою очередь.
        chain = NPCS[q["npc"]]["quests"] if q["npc"] in NPCS else []
        idx = chain.index(qid) if qid in chain else -1
        want = chain[idx - 1] if idx > 0 else None
        if q.get("requires") != want:
            problems.append(f"{qid}: requires={q.get('requires')}, а по цепочке {want}")

    for lid, l in LORE.items():
        if l["npc"] not in NPCS:
            problems.append(f"{lid}: неизвестный персонаж {l['npc']}")
    used = {n["intro"] for n in NPCS.values()} | {q["lore"] for q in QUESTS.values()}
    for lid in LORE:
        if lid not in used:
            problems.append(f"{lid}: фрагмент лора ничем не открывается")

    if problems:
        raise SystemExit("Ловчий Дом не сходится:\n  " + "\n  ".join(problems))
    return True


def _validate_goal(qid, g, enemies, bosses, arenas, characters, curses, danger_max):
    problems = []
    metric = g.get("metric")
    if metric not in METRICS:
        problems.append(f"{qid}: неизвестная метрика {metric}")
    if g.get("scope") not in ("run", "total"):
        problems.append(f"{qid}: scope должен быть run или total")
    if not isinstance(g.get("value"), int) or g["value"] <= 0:
        problems.append(f"{qid}: value должен быть положительным целым")
    # «runs» считает сами забеги: за один забег их всегда один, копить можно
    # только по истории, поэтому scope run для него бессмыслен.
    if metric == "runs" and g.get("scope") != "total":
        problems.append(f"{qid}: metric runs требует scope total")
    if metric == "kills_type":
        tgt = g.get("target")
        if tgt not in enemies and tgt not in bosses:
            problems.append(f"{qid}: цель {tgt} не враг и не босс")
    elif g.get("target"):
        problems.append(f"{qid}: target имеет смысл только для kills_type")

    flt = g.get("filter") or {}
    for key in flt:
        if key not in FILTER_FIELDS:
            problems.append(f"{qid}: движок не знает поля фильтра {key}")
    if "arena" in flt and flt["arena"] not in arenas:
        problems.append(f"{qid}: арена {flt['arena']} не существует")
    if "character" in flt and flt["character"] not in characters:
        problems.append(f"{qid}: персонаж {flt['character']} не существует")
    if "curse" in flt and flt["curse"] not in curses:
        problems.append(f"{qid}: проклятие {flt['curse']} не существует")
    if "danger_min" in flt and not 0 <= flt["danger_min"] <= danger_max:
        problems.append(f"{qid}: danger_min вне диапазона 0..{danger_max}")
    return problems
