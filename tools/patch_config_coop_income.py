#!/usr/bin/env python3
"""Патч: доход коопа на голову приводится к соло по ИЗМЕРЕННОМУ росту убийств.

Что было не так. Компенсация дропа считалась как `N / (1 + budget_per_player*(N-1))`,
то есть по ПЛАНОВОМУ росту спавна. Но доход зависит не от того, сколько врагов
выпущено, а от того, сколько убито, — а доля дожития РАСТЁТ вместе с плотностью
огня в комнате: чем больше народу, тем меньше врагов доживает до конца волны.

Замер `node tools/coop_income.js`, 5 сидов × 10 волн, сложность 1:

    состав |  убийств | рост убийств | плановый рост спавна
         1 |      682 |         1.00 |                 1.00
         2 |     1166 |         1.71 |                 1.65
         3 |     1647 |         2.41 |                 2.30
         4 |     2099 |         3.08 |                 2.95
         5 |     2540 |         3.72 |                 3.60
         6 |     2973 |         4.36 |                 4.25
         7 |     3423 |         5.02 |                 4.90
         8 |     3767 |         5.52 |                 5.55

Реальный рост систематически выше планового: спавн задаёт, сколько врагов
ВЫПУЩЕНО, а доход зависит от того, сколько их УБИТО, и доля дожития растёт вместе
с плотностью огня в комнате. Разрыв небольшой, но односторонний — он и давал
коопу лишние проценты на голову.

ИСТОРИЯ ЗАМЕРА. Первая версия таблицы (2.21 / 3.56 / 5.47 / … / 9.29) снималась,
когда инженерия по ошибке разворачивала В УСТАНОВКИ КАЖДОЕ оружие, а не только
класс `engi`. Тогда весь урон уезжал в разбросанные по карте точки, доля дожития
менялась кратно, и рост убийств выходил вдвое выше нынешнего. После починки гейта
таблицу пришлось переснять целиком: она измеренная, и меряет то состояние игры,
в котором снята.

Что делает патч. Заводит `coop.kill_scale` — измеренную таблицу роста убийств на
каждый состав. `economy.dropFactor` теперь делит N на неё, а не на плановый рост.

Плотность врагов НЕ трогается: `budget_per_player` остаётся 0.65, спавн выпускает
столько же. Меняется только прах, и фактор компенсации разложен на две части:
`dropChance = min(1, factor)`, `dropAmount = max(1, factor)`. Меньше единицы —
прах падает НЕ С КАЖДОГО врага, но кучка полноразмерная (кучка в 0.7 праха
читается как обман, а «падает не с каждого» — понятное правило, и вдвое меньше
пикапов в пуле и в сетевом канале). Больше единицы — падает со всех, кучки
крупнее. При нынешней калибровке фактор 1.17…1.46, то есть режим второй.

Таблица измеренная, а не выведенная: она меряет то состояние игры, в котором
снята. Сменится разброс установок, число копий, `budget_per_player` или список
инженерных классов — переснимать тем же инструментом.

Заодно из HUD убраны «Котёл» и «Твоя доля» (см. DROP_TEXTS ниже).

Идемпотентен, пишет в обе копии конфига (CLAUDE.md §3.2).

    tools/patch_config_coop_income.py --apply
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.join(ROOT, "config", "game_config.json")
LIVE = os.path.join(os.environ.get("ASH_DATA", os.path.join(ROOT, "data")),
                    "game_config.json")

CONTENT_VERSION = 49

COOP = {
    # Во сколько раз комната из N человек убивает больше одиночки. Индекс = N-1.
    # Измерено tools/coop_income.js, НЕ выведено формулой: доля дожития врага
    # зависит от плотности огня, а её формулы у нас нет.
    #
    # Шесть сидов, двумя заходами по три. Второй заход понадобился не для
    # точности ради точности: жребий дропа тянет тот же rng забега, что и выбор
    # типа врага, поэтому включение вероятностного дропа само сдвигает поток и
    # слегка меняет состав волны. Числа обоих заходов — выборки одной и той же
    # величины, и в таблице лежит их среднее. Разброс между заходами доходит до
    # 20% на двоих — это и есть шум, ниже которого калибровку не опустить.
    "kill_scale": [1.0, 1.71, 2.41, 3.08, 3.72, 4.36, 5.02, 5.52],
}


# Строки HUD, которые больше не рисуются. В коопе над прахом висели ещё «Котёл» и
# «Твоя доля»: три числа про одни и те же деньги, из которых два не значат ничего
# в отрыве от состава комнаты. Котёл растёт от чужих убийств и пугает, доля
# дублирует прах с точностью до потраченного. Осталась одна строка — та, на
# которую игрок может что-то купить. Сама механика котла в sim/economy.js не
# тронута, убрана только витрина.
DROP_TEXTS = ["ui.hud.pot", "ui.hud.share"]


def patch(cfg):
    changed = []

    coop = cfg.setdefault("coop", {})
    for k, v in COOP.items():
        if coop.get(k) != v:
            changed.append(f"coop.{k}: {coop.get(k)!r} → {v!r}")
            coop[k] = v

    for lang, texts in cfg.get("i18n", {}).items():
        for k in DROP_TEXTS:
            if k in texts:
                del texts[k]
                changed.append(f"i18n.{lang}.{k} убран")

    if changed and cfg.get("content_version", 0) < CONTENT_VERSION:
        cfg["content_version"] = CONTENT_VERSION
        changed.append(f"content_version → {CONTENT_VERSION}")

    return changed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()

    targets = [REPO] + ([LIVE] if os.path.exists(LIVE) else [])
    for path in targets:
        with open(path, encoding="utf-8") as f:
            cfg = json.load(f)
        changed = patch(cfg)
        print(f"=== {path} ===")
        if not changed:
            print("  (без изменений)")
            continue
        for c in changed:
            print(f"  + {c}")
        if a.apply:
            with open(path, "w", encoding="utf-8") as f:
                json.dump(cfg, f, ensure_ascii=False, indent=2)
                f.write("\n")
            print("  записано")
        else:
            print("  (dry-run, передай --apply)")


if __name__ == "__main__":
    main()
